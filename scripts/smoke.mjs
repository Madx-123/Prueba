import assert from 'node:assert/strict';
import { api } from '../js/services/api.js';
import { CHANNELS } from '../js/data/seed.js';
import { blankCompany, blankEditor } from '../js/core/state.js';
import { previewView } from '../js/views/previews.js';
import { buildCopy } from '../js/features/copyGenerator.js';
import { landingView, authView } from '../js/views/public.js';
import { onboardingView } from '../js/views/onboarding.js';
import { dashboardView } from '../js/views/dashboard.js';
import { readFileSync } from 'node:fs';
let count=0;
const check=(condition,message)=>{assert.ok(condition,message);count++;};
const company={...blankCompany(),id:1,name:'Tienda Sol',sector:'Comercio y retail',channels:['Facebook']};
check(landingView().includes('hero-copy'),'landing');
check(authView('register').includes('name="nombre"'),'registration fields');
check(!authView('login').includes('data-action="demo-login"'),'no simulated login');
for(const channel of CHANNELS){
 const text=buildCopy({channel:channel.id,objective:'Presentar un producto',topic:'Lanzamiento de pan artesanal'},company);
 check(text.includes('pan artesanal'),'template');
 check(previewView(channel.id,text,company).includes('aria-label'),'preview');
}
check(previewView('Facebook','<script>alert(1)</script>',company).includes('&lt;script&gt;'),'escaping');
for(let step=0;step<4;step++) check(onboardingView({onboarding:company,onboardingStep:step}).includes(`ETAPA 0${step+1}`),'onboarding stage');
check(dashboardView({view:'create',user:{name:'Prueba'},company,posts:[],editor:blankEditor(),previewChannel:'Facebook'}).includes('data-action="save-post"'),'editor');
const calls=[];
let failure=false;
globalThis.fetch=async(url,opts)=>{
 calls.push({url,opts});
 const action=url.searchParams.get('action');
 return {ok:!failure,status:failure?500:200,json:async()=>failure?{error:'Fallo MySQL'}:action==='session'?{user:null,csrf:'test-token'}:company};
};
await api.session();
await api.saveCompany(company);
const call=calls.at(-1);
check(call.opts.method==='POST','write uses POST');
check(call.opts.headers['X-CSRF-Token']==='test-token','CSRF');
check(JSON.parse(call.opts.body).name==='Tienda Sol','payload');
check(call.url.pathname.endsWith('/api/index.php'),'relative endpoint');
failure=true;
await assert.rejects(api.saveCompany(company),/Fallo MySQL/);count++;
globalThis.fetch=async()=>({ok:true,json:async()=>{throw Error('HTML');}});
await assert.rejects(api.login({email:'x@y.pe',password:'123456'}),/PHP\/Apache/);count++;
const app=readFileSync(new URL('../js/app.js',import.meta.url),'utf8');
check(!app.includes("document.addEventListener('submit'"),'no duplicate submit listener');
check(!app.includes("document.addEventListener('click'"),'no duplicate onboarding listener');
check(!readFileSync(new URL('../js/services/api.js',import.meta.url),'utf8').includes("from './repository.js'"),'no local storage fallback');
console.log(`✓ ${count} verificaciones de vistas y contrato HTTP. Respuestas simuladas; no sustituye integración MySQL.`);
